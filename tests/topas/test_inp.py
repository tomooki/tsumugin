# ---------------- Param のレンダリング (TOPAS の @ / 名前 / ! の意味論) ----------------


def test_fixed_anonymous_param_is_a_bare_number():
    assert render_param(Param(9.18)) == "9.18"


def test_refined_anonymous_param_uses_at_sign():
    assert render_param(Param(9.18, refine=True)) == "@ 9.18"


def test_refined_named_param_is_name_then_value():
    """TOPAS では名前付きパラメータは既定で精密化対象 (`a lpa1 9.18`)。"""
    assert render_param(Param(9.18, refine=True, name="lpa1")) == "lpa1 9.18"


def test_fixed_named_param_is_prefixed_with_bang():
    """`!` 接頭辞が「名前は付けるが精密化しない」を表す (共有参照先の固定値に使う)。"""
    assert render_param(Param(9.18, name="lpa1")) == "!lpa1 9.18"


def test_bounds_are_appended_as_min_max():
    out = render_param(Param(9.18, refine=True, minimum=9.0, maximum=9.3))
    assert out == "@ 9.18 min 9.0 max 9.3"


def test_reference_renders_as_equation():
    """他パラメータの参照は `=name;` (joint の構造共有で使う中核)。"""
    assert render_param(Param.reference("lpa1")) == "=lpa1;"


def test_param_is_frozen():
    with pytest.raises(Exception):
        Param(1.0).value = 2.0  # type: ignore[misc]


