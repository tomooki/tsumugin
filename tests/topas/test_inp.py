def _pbso4_phase(**kw) -> TopasPhase:
    return TopasPhase(
        phase_name="PbSO4",
        space_group="P_n_m_a",
        cell={"a": Param(8.482), "b": Param(5.397), "c": Param(6.959)},
        sites=(
            TopasSite("Pb", "Pb+2", Param(0.1879), Param(0.25), Param(0.1667), beq=Param(1.5)),
            TopasSite("S", "S", Param(0.4367), Param(0.75), Param(0.1842), beq=Param(0.7)),
        ),
        **kw,
    )


def _histogram(**kw) -> TopasHistogram:
    return TopasHistogram(
        data_path="pbso4.xye",
        preamble=("CuKa5(0.001)", "LP_Factor(26.37)"),
        background=Param(0.0, refine=True),
        background_coeffs=6,
        **kw,
    )


